"""Convert the Gitleaks content-rule catalog to prompt-leaks TOML.

This imports rule data, not Gitleaks runtime code. RE2 expressions are adapted
to Python's ``re`` syntax and compiled before output is written.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import tomllib
from pathlib import Path
from typing import Any


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path, help="Gitleaks config/gitleaks.toml")
    parser.add_argument("output", type=Path, help="prompt-leaks TOML output")
    args = parser.parse_args()

    source = args.source.resolve()
    data = tomllib.loads(source.read_text(encoding="utf-8"))
    commit = _git_commit(source.parent)
    rendered, imported, omitted = render_catalog(data, commit=commit)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Imported {imported} content rules; omitted {omitted} path-only rules.")
    return 0


def render_catalog(data: dict[str, Any], *, commit: str) -> tuple[str, int, int]:
    lines = [
        "# Generated by scripts/import_gitleaks_rules.py. Do not edit manually.",
        "#",
        "# Source: https://github.com/gitleaks/gitleaks/blob/master/config/gitleaks.toml",
        f"# Source commit: {commit}",
        "# Gitleaks is MIT licensed; see THIRD_PARTY_NOTICES.md.",
        "#",
        "# Prompt adaptation:",
        "# - content rules are retained; the path-only pkcs12-file rule is omitted;",
        "# - rule path constraints and path/commit allowlist criteria are omitted;",
        "# - RE2 bare (?i) flags, \\z, and POSIX alnum are translated for Python re.",
        "",
        f"catalog_title = {_string(data.get('title', 'Gitleaks rules'))}",
        f"catalog_min_version = {_string(data.get('minVersion', 'unknown'))}",
        f"catalog_source_commit = {_string(commit)}",
        "",
    ]

    global_allowlist = data.get("allowlist")
    if global_allowlist:
        rendered = _render_allowlist(global_allowlist, header="[[allowlists]]")
        if rendered:
            lines.extend(rendered)

    imported = 0
    omitted = 0
    for source_rule in data.get("rules", []):
        if "regex" not in source_rule:
            omitted += 1
            continue
        imported += 1
        lines.extend(_render_rule(source_rule))

    lines.extend(_render_prompt_extensions())

    return "\n".join(lines).rstrip() + "\n", imported, omitted


