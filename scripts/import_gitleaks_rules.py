def _render_rule(rule: dict[str, Any]) -> list[str]:
    rule_id = str(rule["id"])
    regex, flags = _translate_regex(str(rule["regex"]), context=rule_id)
    lines = [
        "[[rules]]",
        f"id = {_string(rule_id)}",
        f"description = {_string(str(rule.get('description', rule_id)))}",
        f"regex = {_string(regex)}",
    ]
    if flags:
        lines.append(f"flags = {_array(flags)}")
    if rule.get("keywords"):
        lines.append(f"keywords = {_array(rule['keywords'])}")
    if "secretGroup" in rule:
        lines.append(f"secret_group = {int(rule['secretGroup'])}")
    if rule.get("entropy"):
        lines.append(f"entropy = {float(rule['entropy']):g}")
    if rule.get("tags"):
        lines.append(f"tags = {_array(rule['tags'])}")

    is_generic = "generic" in rule_id.casefold()
    lines.append(f"generic = {'true' if is_generic else 'false'}")
    lines.append(f"priority = {40 if is_generic else 100}")
    if rule.get("validator"):
        lines.append(f"validator = {_string(rule['validator'])}")
    if rule.get("severity"):
        lines.append(f"severity = {_string(rule['severity'])}")
    if "confidence" in rule:
        lines.append(f"confidence = {float(rule['confidence']):g}")
    if rule.get("path"):
        lines.append(f"source_path_constraint = {_string(str(rule['path']))}")
    lines.append("")

    allowlists = list(rule.get("allowlists", []))
    legacy = rule.get("allowlist")
    if legacy:
        allowlists.append(legacy)
    for allowlist in allowlists:
        rendered = _render_allowlist(
            allowlist,
            header="[[rules.allowlists]]",
            context=f"{rule_id} allowlist",
        )
        if rendered:
            lines.extend(rendered)
    return lines


def _render_allowlist(
    allowlist: dict[str, Any],
    *,
    header: str,
    context: str = "global allowlist",
) -> list[str]:
    regexes: list[str] = []
    flags: set[str] = set()
    for source_regex in allowlist.get("regexes", []):
        regex, regex_flags = _translate_regex(str(source_regex), context=context)
        regexes.append(regex)
        flags.update(regex_flags)

    stop_words = [str(value) for value in allowlist.get("stopwords", [])]
    if not regexes and not stop_words:
        return []

    target = str(allowlist.get("regexTarget", "secret"))
    lines = [header, f"target = {_string(target)}"]
    if flags:
        lines.append(f"flags = {_array(sorted(flags))}")
    if regexes:
        lines.append(f"regexes = {_array(regexes)}")
    if stop_words:
        lines.append(f"stop_words = {_array(stop_words)}")
    if str(allowlist.get("condition", "OR")).upper() == "AND":
        lines.append("# Upstream condition was AND with a path criterion; path is not applicable to prompts.")
    lines.append("")
    return lines


def _translate_regex(pattern: str, *, context: str) -> tuple[str, list[str]]:
    flags: list[str] = []
    if "(?i)" in pattern:
        pattern = pattern.replace("(?i)", "")
        flags.append("IGNORECASE")
    pattern = pattern.replace(r"\z", r"\Z")
    pattern = pattern.replace("[[:alnum:]]", "[A-Za-z0-9]")
    try:
        re.compile(pattern, re.IGNORECASE if "IGNORECASE" in flags else 0)
    except re.error as error:
        raise ValueError(f"unable to translate {context}: {error}") from error
    return pattern, flags


def _string(value: Any) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _array(values: Any) -> str:
    return "[" + ", ".join(_string(value) for value in values) + "]"


def _git_commit(start: Path) -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(start), "rev-parse", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


